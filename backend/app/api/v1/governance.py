@router.post("/board-packs", response_model=BoardPackRead, status_code=201, dependencies=[_WRITE],
             summary="Generate a board pack (PDF + XLSX) for a committee, a meeting or the organisation")
async def create_board_pack(body: BoardPackCreate, db: DbSession, user: CurrentUser) -> BoardPackRead:
    """Builds the pack now. The period defaults to the fiscal quarter to date; a period
    ending in the future, an unknown section or a meeting of another committee is a 422.
    A failure while building or rendering is kept on the returned pack (status
    ``failed`` with the reason) rather than lost."""
    committee = meeting = None
    if body.meeting_id is not None:
        meeting = await _load_meeting(db, body.meeting_id)
        if body.committee_id is not None and body.committee_id != meeting.committee_id:
            raise HTTPException(status_code=422, detail="meeting_id: that meeting belongs to another committee.")
        committee = await _load_committee(db, meeting.committee_id)
    elif body.committee_id is not None:
        committee = await _load_committee(db, body.committee_id)
    org = await board_pack.org_context(db, user.tenant_id)
    try:
        pack = await board_pack.generate(
            db, org, actor=user, committee=committee, meeting=meeting,
            period_start=body.period_start, period_end=body.period_end,
            sections=body.sections, title=body.title,
        )
    except board_pack.PackError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    return (await _pack_reads(db, [pack], user))[0]


@router.get("/board-packs", response_model=Page[BoardPackRead], dependencies=[_READ],
            summary="Board packs, newest first")
async def list_board_packs(
    db: DbSession,
    user: CurrentUser,
    committee_id: uuid.UUID | None = None,
    meeting_id: uuid.UUID | None = None,
    status_filter: Annotated[str | None, Query(alias="status", pattern="^(ready|failed)$")] = None,
    review_state: Annotated[str | None, Query(pattern="^(draft|reviewed|released)$")] = None,
    limit: Annotated[int, Query(ge=1, le=200)] = 50,
    offset: Annotated[int, Query(ge=0)] = 0,
) -> Page[BoardPackRead]:
    stmt = select(BoardPack)
    # Someone who can't prepare packs (a board member) sees released packs only.
    if user is not None and "governance:write" not in set(user.permission_codes or []):
        stmt = stmt.where(BoardPack.review_state == board_pack.RELEASED)
    if review_state is not None:
        stmt = stmt.where(BoardPack.review_state == review_state)
    if committee_id is not None:
        stmt = stmt.where(BoardPack.committee_id == committee_id)
    if meeting_id is not None:
        stmt = stmt.where(BoardPack.meeting_id == meeting_id)
    if status_filter is not None:
        stmt = stmt.where(BoardPack.status == status_filter)
    total = await db.scalar(select(func.count()).select_from(stmt.subquery())) or 0
    rows = (await db.scalars(
        stmt.order_by(BoardPack.generated_at.desc().nulls_last(), BoardPack.created_at.desc())
        .limit(limit).offset(offset)
    )).all()
    return Page(items=await _pack_reads(db, rows, user), total=total, limit=limit, offset=offset)


