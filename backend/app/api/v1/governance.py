async def _load_meeting(db, mid: uuid.UUID) -> Meeting:
    # Meetings have no archive flag of their own (they are deleted outright); a meeting
    # of an archived committee is gone with it. (This used to filter on a
    # ``Meeting.deleted`` column that does not exist, so every call failed.)
    obj = await db.scalar(
        select(Meeting)
        .join(Committee, Committee.id == Meeting.committee_id)
        .where(Meeting.id == mid, Committee.deleted.is_(False))
        .execution_options(populate_existing=True)
    )
    if obj is None:
        raise HTTPException(status_code=404, detail="Meeting not found")
    return obj


