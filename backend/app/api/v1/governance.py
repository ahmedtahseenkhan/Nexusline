def _plain(value):
    return getattr(value, "value", value)


#: Fields that may be cleared (sent as null); every other null in a PATCH is ignored.
_NULLABLE_COMMITTEE_FIELDS = frozenset({"board_pack_days_before", "board_pack_sections"})


@router.patch("/governance/{cid}", response_model=CommitteeRead, dependencies=[_WRITE])
async def update_committee(cid: uuid.UUID, body: CommitteeUpdate, db: DbSession, user: CurrentUser) -> CommitteeRead:
    obj = await _load_committee(db, cid)
    changes: dict = {}
    for k, v in body.model_dump(exclude_unset=True).items():
        if v is None and k not in _NULLABLE_COMMITTEE_FIELDS:
            continue
        if k == "board_pack_sections":
            v = _sections_or_422(v)
        before = getattr(obj, k)
        if before != v:
            changes[k] = {"from": _plain(before), "to": _plain(v)}
        setattr(obj, k, v)
    await db.flush()
    if changes:
        auto = changes.get("board_pack_days_before")
        note = ""
        if auto is not None:
            note = (f"; board pack generated {auto['to']} day(s) before each meeting" if auto["to"]
                    else "; board pack no longer generated automatically")
        await audit_log.record(db, actor=user, action="update", entity_type="committee", entity_id=obj.id,
                               summary=f"Updated committee {obj.reference}: {', '.join(changes)}{note}"[:500],
                               changes=changes)
    return CommitteeRead.model_validate(await _load_committee(db, cid))


